      'erreurs à éviter',
      'plan de repas',
      'objectifs du plan',
      'liste de courses',
      'conseils de préparation',
      'petit-déjeuner',
      'déjeuner',
      'dîner',
      'collation',
      'collations',
      'resumen',
      'recomendaciones clave',
      'recomendaciones',
      'estrategia',
      'plan de acción',
      'plan paso a paso',
      'ejemplos',
      'plantilla',
      'próximo paso',
      'errores comunes que debes evitar',
      'plan de comidas',
      'objetivos del plan',
      'lista de compras',
      'consejos de preparación',
      'desayuno',
      'almuerzo',
      'cena',
      'merienda',
      'meriendas',
    };

    for (final line in lines) {
      final clean = line.trim();

      if (clean.isEmpty) {
        widgets.add(pw.SizedBox(height: 5));
        continue;
      }

      final lower = clean.toLowerCase().replaceAll(':', '').trim();
      final isNumbered = RegExp(r'^\d+\.\s+').hasMatch(clean);
      final isBullet = clean.startsWith('- ');

      final isHeading =
          commonHeadings.contains(lower) ||
          (
            clean.length <= 48 &&
            !clean.endsWith('.') &&
            !isNumbered &&
            !isBullet &&
            !clean.contains(',')
          );

      if (isHeading) {
        widgets.add(
          pw.Container(
            margin: const pw.EdgeInsets.only(top: 12, bottom: 5),
            padding: const pw.EdgeInsets.only(bottom: 3),
            decoration: pw.BoxDecoration(
              border: pw.Border(
                bottom: pw.BorderSide(
                  color: PdfColor.fromHex('#E5E7EB'),
                  width: 0.6,
                ),
              ),
            ),
            child: pw.Text(
              clean.replaceAll(':', ''),
              style: pw.TextStyle(
                fontSize: 12.5,
                fontWeight: pw.FontWeight.bold,
                color: PdfColor.fromHex('#111827'),
              ),
            ),
          ),
        );
        continue;
      }

      if (isNumbered && clean.length <= 95) {
        widgets.add(
          pw.Container(
            margin: const pw.EdgeInsets.only(top: 7, bottom: 3),
            child: pw.Text(
              clean,
              style: pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
                color: PdfColor.fromHex('#111827'),
              ),
            ),
          ),
        );
        continue;
      }

      if (isBullet) {
        widgets.add(
          pw.Padding(
            padding: const pw.EdgeInsets.only(left: 10, bottom: 3),
            child: pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Container(
                  width: 3.5,
                  height: 3.5,
                  margin: const pw.EdgeInsets.only(top: 5, right: 7),
                  decoration: pw.BoxDecoration(
                    color: PdfColor.fromHex('#111827'),
                    shape: pw.BoxShape.circle,
                  ),
                ),
                pw.Expanded(
                  child: pw.Text(
                    clean.substring(2),
                    style: const pw.TextStyle(
                      fontSize: 10,
                      lineSpacing: 2,
                    ),
                  ),
                ),
              ],
            ),
          ),
        );
        continue;
      }

      widgets.add(
        pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 5.5),
          child: pw.Text(
            clean,
            style: const pw.TextStyle(
              fontSize: 10,
              lineSpacing: 2,
            ),
          ),
        ),
      );
    }

    return widgets;
  }


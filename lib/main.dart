  Future<void> _generate() async {
    final command = _controller.text.trim();

    if (command.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(_t.commandEmpty)),
      );
      return;
    }

    setState(() {
      _loading = true;
      _error = null;
    });

    try {
      final response = await http
          .post(
            Uri.parse(backendUrl()),
            headers: {'Content-Type': 'application/json'},
            body: jsonEncode({
              'command': command,
              'language': _selectedLanguage,
            }),
          )
          .timeout(const Duration(seconds: 90));

      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw Exception(response.body);
      }

      final data = jsonDecode(response.body) as Map<String, dynamic>;
      final content = (data['content'] ?? '').toString().trim();

      if (content.isEmpty) {
        throw Exception('No AI content returned.');
      }

      setState(() {
        _loading = false;
        _controller.clear();
        _files.insert(
          0,
          GeneratedFile(
            command: command,
            fileName: _makeFileName(command),
            content: content,
          ),
        );
      });
    } catch (error) {
      setState(() {
        _loading = false;
        _error = _t.createError;
      });
    }
  }

  String _makeFileName(String text) {
    final words = RegExp(r'[A-Za-z0-9]+')
        .allMatches(text)
        .map((match) => match.group(0)!)
        .take(5)
        .toList();

    if (words.isEmpty) {
      return 'Chee_Chai_Chee_Output.pdf';
    }

    return '${words.join('_')}.pdf';
  }

  String _cleanMarkdown(String text) {
    var value = text
        .replaceAll('\r', '')
        .replaceAll('**', '')
        .replaceAll('__', '')
        .replaceAll('`', '')
        .replaceAll('�', "'")
        .replaceAll('’', "'")
        .replaceAll('‘', "'")
        .replaceAll('“', '"')
        .replaceAll('”', '"')
        .replaceAll('–', '-')
        .replaceAll('—', '-')
        .replaceAll(RegExp(r'^#{1,6}\s*'), '')
        .replaceAll(RegExp(r'[✅☑✔✓☐☒]'), '-')
        .replaceAll(RegExp(r'[•●▪▫◦]'), '-')
        .trim();

    value = value.replaceAll(RegExp(r'\s+'), ' ');

    return value.trim();
  }

  String _cleanDisplayText(String text) {
    final lines = text.replaceAll('\r\n', '\n').split('\n');
    final output = <String>[];

    bool skipNextTitleValue = false;

    for (final line in lines) {
      final cleaned = _cleanMarkdown(line.trim());

      if (cleaned.isEmpty) {
        if (output.isNotEmpty && output.last.isNotEmpty) {
          output.add('');
        }
        continue;
      }

      final lower = cleaned.toLowerCase();

      if (['title', 'titre', 'título', 'titulo'].contains(lower)) {
        skipNextTitleValue = true;
        continue;
      }

      if (skipNextTitleValue) {
        skipNextTitleValue = false;
        continue;
      }

      output.add(cleaned);
    }

    return output.join('\n').replaceAll(RegExp(r'\n{3,}'), '\n\n').trim();
  }

  String _documentTitleFromCommand(String command) {
    final clean = _cleanMarkdown(command.trim());

    if (clean.isEmpty) {
      return 'Chee Chai Chee Output';
    }

    final withoutQuestion = clean.replaceAll('?', '').trim();

    if (withoutQuestion.length <= 56) {
      return withoutQuestion[0].toUpperCase() + withoutQuestion.substring(1);
    }

    final words = RegExp(r'[A-Za-zÀ-ÿ0-9]+')
        .allMatches(withoutQuestion)
        .map((match) => match.group(0)!)
        .take(7)
        .toList();

    if (words.isEmpty) {
      return 'Chee Chai Chee Output';
    }

    return words.join(' ');
  }

